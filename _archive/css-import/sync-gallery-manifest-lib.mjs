import {readdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

const SKIP_DIRS = new Set(['_shared', '_generated']);

// Post126SlideFly: manual composition in manual-compositions.tsx (slide-fly preset).
// No template meta.json — reuses post-126/schema.ts propsFields at sync time.
const MANUAL_PICKER_IDS = ['Post126SlideFly'];

export async function syncGalleryManifest(studioRoot) {
  const templatesRoot = path.join(studioRoot, 'src', 'templates');
  const galleryDir = path.join(studioRoot, 'src', 'gallery');
  const entries = await readdir(templatesRoot, {withFileTypes: true});

  const metas = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || SKIP_DIRS.has(entry.name)) continue;
    const metaPath = path.join(templatesRoot, entry.name, 'meta.json');
    try {
      const raw = await readFile(metaPath, 'utf8');
      metas.push({dir: entry.name, ...JSON.parse(raw)});
    } catch {
      // skip dirs without meta
    }
  }

  metas.sort((a, b) => a.id.localeCompare(b.id));

  const imports = metas
    .map(
      (m) =>
        `import {schema as schema_${m.dir.replace(/-/g, '_')}, DURATION as duration_${m.dir.replace(/-/g, '_')}} from '../templates/${m.dir}/schema';
import {SoftFloatCard as Card_${m.dir.replace(/-/g, '_')}} from '../templates/${m.dir}/presets/soft-float';`,
    )
    .join('\n');

  const compositions = metas
    .map((m) => {
      const d = m.dir.replace(/-/g, '_');
      return `  {
    id: '${m.id}',
    duration: duration_${d},
    schema: schema_${d},
    defaultProps: ${JSON.stringify(m.defaultProps ?? {}, null, 6).replace(/\n/g, '\n    ')},
    Component: makeComposition(Card_${d}, duration_${d}),
  }`;
    })
    .join(',\n');

  const manifestTs = `/* AUTO-GENERATED by npm run sync:gallery — do not edit by hand */
import React from 'react';
import {AbsoluteFill, staticFile, useCurrentFrame} from 'remotion';
${imports}

function makeComposition(Card: React.ComponentType<any>, segmentFrames: number) {
  const Wrapped: React.FC<Record<string, unknown>> = (props) => {
    const frame = useCurrentFrame();
    const image = typeof props.image === 'string' ? props.image : 'generated/post-126.png';
    return (
      <AbsoluteFill style={{alignItems: 'center', justifyContent: 'center', background: '#c8ccd0'}}>
        <Card
          card={props}
          localFrame={frame}
          segmentFrames={segmentFrames}
          imageSrc={staticFile(image)}
        />
      </AbsoluteFill>
    );
  };
  return Wrapped;
}

export const GALLERY_COMPOSITIONS = [
${compositions}
] as const;
`;

  const projectsPath = path.join(studioRoot, 'src', 'projects.json');
  const projectsRaw = await readFile(projectsPath, 'utf8');
  const {projects} = JSON.parse(projectsRaw);

  const pickerEntries = metas.map((m) => ({
    id: m.id,
    project: m.project || 'am-news',
    name: m.name,
    description: m.description || '',
    tag: m.tag || 'Template',
    propsFields: m.propsFields ?? [],
  }));

  const post126Meta = metas.find((m) => m.id === 'Post126SoftFloat');
  for (const manualId of MANUAL_PICKER_IDS) {
    if (manualId === 'Post126SlideFly') {
      pickerEntries.push({
        id: 'Post126SlideFly',
        project: 'am-news',
        name: 'AM News — Slide Fly',
        description: 'Влет слева, справа и снизу, затем лёгкий горизонтальный drift.',
        tag: 'Динамичная',
        propsFields: post126Meta?.propsFields ?? [],
      });
    }
  }

  pickerEntries.sort((a, b) => a.name.localeCompare(b.name));

  await writeFile(path.join(galleryDir, 'composition-manifest.tsx'), manifestTs);
  await writeFile(
    path.join(galleryDir, 'templates.json'),
    `${JSON.stringify({projects, templates: pickerEntries}, null, 2)}\n`,
  );

  return {count: metas.length, ids: metas.map((m) => m.id)};
}
